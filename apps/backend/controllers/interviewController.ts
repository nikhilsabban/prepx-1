/**
 * Retrieves full interview result & evaluation (powered by Groq openai/gpt-oss-120b)
 */
export async function getResult(req: Request, res: Response): Promise<void> {
  try {
    const { interviewId } = req.params;

    const interview = await Interview.findById(interviewId);
    if (!interview) {
      res.status(404).json({ message: "Interview not found" });
      return;
    }

    const conversations = await Message.find({ interviewId }).sort({ createdAt: 1 });

    const transcript = conversations.map((c) => ({
      type: c.type,
      content: c.message,
      createdAt: c.createdAt,
    }));

    if (interview.status !== "Done" && conversations.length > 0) {
      try {
        const result = await calculateResult(
          conversations.map((c) => ({
            type: c.type,
            message: c.message,
            createdAt: c.createdAt,
          }))
        );

        interview.status = "Done";
        interview.score = result.overallScore || result.score || 0;
        interview.feedback = result.overallFeedback || result.feedback || "";
        interview.evaluationData = result;
        await interview.save();

        // Award +150 XP to candidate upon completing interview round
        if (interview.userId) {
          const User = (await import("../models/User")).User;
          const userObj = await User.findById(interview.userId);
          if (userObj) {
            userObj.xp = (userObj.xp || 0) + 150;
            // Update streak if active
            const now = new Date();
            const lastActive = userObj.lastActiveDate ? new Date(userObj.lastActiveDate) : null;
            if (!lastActive || (now.getTime() - lastActive.getTime()) > 24 * 60 * 60 * 1000) {
              userObj.streakDays = (userObj.streakDays || 1) + 1;
              userObj.lastActiveDate = now;
            }
            if (interview.score >= 9 && !userObj.badges?.includes("Ace Candidate")) {
              userObj.badges = [...(userObj.badges || []), "Ace Candidate"];
            }
            await userObj.save();
          }
        }
      } catch (calcError) {
        console.error("Groq AI Evaluation error:", calcError);
      }
    }

    res.json({
      score: interview.score,
      feedback: interview.feedback,
      evaluationData: interview.evaluationData,
      transcript,
      status: interview.status,
    });
  } catch (error: any) {
    console.error("Get result error:", error);
    res.status(500).json({ message: error.message || "Failed to retrieve result" });
  }
}

/**
 * Toggles bookmark status of an interview or question item
 */
export async function toggleBookmark(req: AuthRequest, res: Response): Promise<void> {
  try {
    if (!req.user) {
      res.status(401).json({ message: "Not authenticated" });
      return;
    }

    const { interviewId } = req.params;
    const interview = await Interview.findOne({ _id: interviewId, userId: req.user._id });

    if (!interview) {
      res.status(404).json({ message: "Interview record not found" });
      return;
    }

    interview.isBookmarked = !interview.isBookmarked;
    await interview.save();

    res.json({
      success: true,
      isBookmarked: interview.isBookmarked,
      message: interview.isBookmarked ? "Interview bookmarked" : "Bookmark removed",
    });
  } catch (error: any) {
    console.error("Toggle bookmark error:", error);
    res.status(500).json({ message: error.message || "Failed to update bookmark" });
  }
}

