/**
 * Initiates the voice interview with an opening question generated by Groq + Deepgram TTS
 */
export async function initiateInterview(req: AuthRequest, res: Response): Promise<void> {
  try {
    const { interviewId } = req.params;
    const interview = await Interview.findById(interviewId);

    if (!interview) {
      res.status(404).json({ message: "Interview session not found" });
      return;
    }

    // Anti-cheating check: Enforce single device active per interview
    const token = req.headers.authorization ? req.headers.authorization.split(" ")[1] : "";
    if (interview.status === "InProgress" && interview.activeDeviceToken && interview.activeDeviceToken !== token) {
      res.status(403).json({
        message: "This interview session is already active on another device. Multi-device access is blocked for anti-cheating compliance.",
      });
      return;
    }

    if (!interview.activeDeviceToken || interview.status === "Pre") {
      interview.activeDeviceToken = token;
    }

    interview.status = "InProgress";
    await interview.save();

    // Check existing messages
    const existingMessages = await Message.find({ interviewId }).sort({ createdAt: 1 });
    if (existingMessages.length > 0) {
      const lastAiMessage = existingMessages.filter((m) => m.type === "Assistant").pop();
      const text = lastAiMessage ? lastAiMessage.message : "Welcome to your interview! Tell me about your background.";
      const tts = await synthesizeSpeechWithDeepgram(text);

      res.json({
        aiMessage: text,
        audioBase64: tts ? tts.audioBuffer.toString("base64") : null,
        contentType: tts?.contentType || "audio/mp3",
      });
      return;
    }

    // Generate initial welcome question via Groq
    const initialText = await generateInterviewerResponse(
      interview.githubMetadata, 
      [], 
      undefined, 
      interview.difficulty || "Medium"
    );

    // Save AI welcome question
    await Message.create({
      interviewId,
      type: "Assistant",
      message: initialText,
    });

    // Synthesize voice via Deepgram Aura TTS
    const tts = await synthesizeSpeechWithDeepgram(initialText);

    res.json({
      aiMessage: initialText,
      audioBase64: tts ? tts.audioBuffer.toString("base64") : null,
      contentType: tts?.contentType || "audio/mp3",
    });
  } catch (error: any) {
    console.error("Initiate interview error:", error);
    res.status(500).json({ message: error.message || "Failed to initiate session" });
  }
}

/**
 * Processes user candidate speech message via Groq LLM + Deepgram Aura TTS
 */
export async function processInterviewResponse(req: Request, res: Response): Promise<void> {
  try {
    const { interviewId } = req.params;
    const { message } = req.body;

    if (!interviewId || !message || !message.trim()) {
      res.status(400).json({ message: "Interview ID and user transcript message are required" });
      return;
    }

    const interview = await Interview.findById(interviewId);
    if (!interview) {
      res.status(404).json({ message: "Interview session not found" });
      return;
    }

    // Anti-cheating check: Block process response if request comes from different token
    const token = req.headers.authorization ? req.headers.authorization.split(" ")[1] : "";
    if (interview.activeDeviceToken && interview.activeDeviceToken !== token) {
      res.status(403).json({
        message: "Anti-cheating violation: This interview session is bound to another active device.",
      });
      return;
    }

    // 1. Save candidate message in MongoDB
    await Message.create({
      interviewId,
      type: "User",
      message: message.trim(),
    });

    // 2. Fetch all past messages for context
    const conversationHistory = await Message.find({ interviewId }).sort({ createdAt: 1 });
    const formattedTurns = conversationHistory.map((m) => ({
      type: m.type,
      message: m.message,
    }));

    // 3. Generate interviewer follow-up using Groq
    const aiText = await generateInterviewerResponse(
      interview.githubMetadata,
      formattedTurns,
      undefined,
      interview.difficulty || "Medium"
    );

    // 4. Save AI follow-up message in MongoDB
    await Message.create({
      interviewId,
      type: "Assistant",
      message: aiText,
    });

    // 5. Synthesize natural voice using Deepgram Aura TTS
    const tts = await synthesizeSpeechWithDeepgram(aiText);

    res.json({
      aiMessage: aiText,
      audioBase64: tts ? tts.audioBuffer.toString("base64") : null,
      contentType: tts?.contentType || "audio/mp3",
    });
  } catch (error: any) {
    console.error("Process interview response error:", error);
    res.status(500).json({ message: error.message || "Failed to process interview response" });
  }
}

