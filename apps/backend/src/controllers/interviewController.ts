export function parseGithubTarget(input: string, explicitRepoName?: string, interviewTitle?: string): { owner: string; repo?: string } {
  let clean = input.trim().replace(/\/+$/, "").replace(/\.git$/i, "");
  
  let owner = "";
  let repo = explicitRepoName?.trim() || undefined;

  if (clean.includes("github.com/")) {
    const afterDomain = clean.split("github.com/")[1] || "";
    const parts = afterDomain.split("/").filter(Boolean);
    owner = parts[0] || clean;
    if (parts.length >= 2 && !repo) {
      repo = parts[1];
    }
  } else {
    const parts = clean.split("/").filter(Boolean);
    owner = parts[0] || clean;
    if (parts.length >= 2 && !repo) {
      repo = parts[1];
    }
  }

  // Fallback: If repo is still not identified but title explicitly names it
  if (!repo && interviewTitle) {
    const match = interviewTitle.match(/Technical Interview on ([\w.-]+)/i);
    if (match && match[1]) {
      repo = match[1].trim();
    }
  }

  return { owner, repo };
}

/**
 * Creates pre-interview record and scrapes candidate GitHub info
 */
export async function createPreInterview(req: AuthRequest, res: Response): Promise<void> {
  try {
    const { success, data } = PreInterviewBody.safeParse(req.body);

    if (!success) {
      res.status(400).json({
        message: "Interview Title and GitHub URL are mandatory.",
      });
      return;
    }

    const mode = data.mode || (data.github ? "github" : data.jobDescription ? "jd" : "role");
    let githubData: any = {};

    if (mode === "github" && data.github) {
      const { owner, repo } = parseGithubTarget(data.github, (data as any).repoName, data.title);

      if (owner && repo) {
        console.log(`🔍 [Interview Controller] Targeting specific repository: ${owner}/${repo}`);
        githubData = await scrapeSpecificRepo(owner, repo);
      } else if (owner) {
        console.log(`🔍 [Interview Controller] Targeting user profile: ${owner}`);
        githubData = await scrapeGithub(owner);
      }
    } else if (mode === "role") {
      githubData = { targetRole: data.role || "Software Engineer" };
    } else if (mode === "jd") {
      githubData = { jobDescription: data.jobDescription || "" };
    }

    const difficultyLabel = data.difficulty || "Medium";
    const dynamicTitle = data.title.trim();

    const interview = await Interview.create({
      userId: req.user?._id || undefined,
      title: dynamicTitle,
      mode,
      role: data.role || "",
      jobDescription: data.jobDescription || "",
      githubMetadata: githubData,
      difficulty: difficultyLabel,
      status: "Pre",
      score: 0,
      feedback: "",
    });

    res.json({ id: interview._id.toString() });
  } catch (error: any) {
    console.error("Pre-interview error:", error);
    res.status(500).json({
      message: error.message || "Failed to start pre-interview",
    });
  }
}

/**
 * Issues short-lived authorization ticket and metadata for frontend STT WebSocket proxy.
 * Eliminates permanent master DEEPGRAM_API_KEY exposure to client browsers.
 */
export async function getDeepgramKey(req: AuthRequest, res: Response): Promise<void> {
  const isMurfConfigured = !!process.env.MURF_API_KEY?.trim();
  const isConfigured = isMurfConfigured;

  if (!isConfigured) {
    res.json({
      configured: false,
      proxyUrl: "",
      token: "",
      recommendedModel: "murf-stt",
      defaultLanguage: "en-IN",
      provider: "murf",
    });
    return;
  }

  // Issue a short-lived 10-minute STT streaming session ticket
  const payload = {
    sub: req.user?._id || "candidate-session",
    role: (req.user as any)?.role || "candidate",
    purpose: "stt_stream",
  };

  const sttToken = jwt.sign(payload, process.env.JWT_SECRET || "fallback_secret", {
    expiresIn: "10m",
  });

  res.json({
    configured: true,
    proxyUrl: "/api/v1/interview/stt-stream",
    token: sttToken,
    recommendedModel: isMurfConfigured ? "murf-stt" : "nova-2",
    defaultLanguage: "en-IN",
    provider: isMurfConfigured ? "murf" : "deepgram",
  });
}

/**
 * Initiates the voice interview with an opening question generated by Groq + Deepgram TTS
 */
export async function initiateInterview(req: AuthRequest, res: Response): Promise<void> {
  try {
    const { interviewId } = req.params;
    const interview = await Interview.findById(interviewId);

    if (!interview) {
      res.status(404).json({ message: "Interview session not found" });
      return;
    }

    // Session authorization & device token tracking
    const token = req.headers.authorization ? req.headers.authorization.split(" ")[1] : "";

    // If an interview belongs to another authenticated user, prevent access
    if (interview.userId && req.user?._id && interview.userId.toString() !== req.user._id.toString()) {
      res.status(403).json({
        message: "You are not authorized to access another user's interview session.",
      });
      return;
    }

    // Link userId if session was created anonymously and user is now authenticated
    if (!interview.userId && req.user?._id) {
      interview.userId = req.user._id;
    }

    // Always keep activeDeviceToken updated to latest active session
    if (token) {
      interview.activeDeviceToken = token;
    }

    interview.status = "InProgress";
    await Interview.updateOne(
      { _id: interviewId },
      { $set: { status: "InProgress", activeDeviceToken: token || interview.activeDeviceToken, ...(interview.userId ? { userId: interview.userId } : {}) } }
    );

    // Check existing messages
    const existingMessages = await Message.find({ interviewId }).sort({ createdAt: 1 }).lean();
    if (existingMessages.length > 0) {
      const lastAiMessage = existingMessages.filter((m) => m.type === "Assistant").pop();
      const text = lastAiMessage ? lastAiMessage.message : "Welcome to your interview! Tell me about your background.";
      const tts = await synthesizeSpeech(text);

      res.json({
        aiMessage: text,
        audioBase64: tts ? tts.audioBuffer.toString("base64") : null,
        contentType: tts?.contentType || "audio/mp3",
        history: existingMessages.map((m) => ({
          id: m._id.toString(),
          sender: m.type === "Assistant" ? "ai" : "user",
          text: m.message,
          time: new Date(m.createdAt).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
          audioBase64: null,
        })),
      });
      return;
    }

    // Generate initial welcome question via Groq
    const initialText = await generateInterviewerResponse(
      interview.githubMetadata, 
      [], 
      undefined, 
      interview.difficulty || "Medium"
    );

    // Concurrently save AI welcome question and synthesize speech
    const [, tts] = await Promise.all([
      Message.create({
        interviewId,
        type: "Assistant",
        message: initialText,
      }),
      synthesizeSpeech(initialText),
    ]);

    res.json({
      aiMessage: initialText,
      audioBase64: tts ? tts.audioBuffer.toString("base64") : null,
      contentType: tts?.contentType || "audio/mp3",
    });
  } catch (error: any) {
    console.error("Initiate interview error:", error);
    res.status(500).json({ message: error.message || "Failed to initiate session" });
  }
}

/**
 * Processes user candidate speech message via Groq LLM + Deepgram Aura TTS
 */
export async function processInterviewResponse(req: AuthRequest, res: Response): Promise<void> {
  try {
    const { interviewId } = req.params;
    const { message } = req.body;

    if (!interviewId || !message || !message.trim()) {
      res.status(400).json({ message: "Interview ID and user transcript message are required" });
      return;
    }

    const interview = await Interview.findById(interviewId).lean();
    if (!interview) {
      res.status(404).json({ message: "Interview session not found" });
      return;
    }

    // Session authorization & device token tracking
    const token = req.headers.authorization ? req.headers.authorization.split(" ")[1] : "";

    if (interview.userId && req.user?._id && interview.userId.toString() !== req.user._id.toString()) {
      res.status(403).json({
        message: "You are not authorized to respond to this interview session.",
      });
      return;
    }

    if (token && interview.activeDeviceToken !== token) {
      Interview.updateOne({ _id: interviewId }, { $set: { activeDeviceToken: token } }).catch(() => {});
    }

    // 1 & 2. Concurrently save candidate message in MongoDB and fetch conversation history
    const userMsgPromise = Message.create({
      interviewId,
      type: "User",
      message: message.trim(),
    });

    const historyPromise = Message.find({ interviewId }).sort({ createdAt: 1 }).lean();

    const [, conversationHistory] = await Promise.all([userMsgPromise, historyPromise]);

    const formattedTurns = conversationHistory.map((m) => ({
      type: m.type,
      message: m.message,
    }));
    formattedTurns.push({ type: "User", message: message.trim() });

    // 3. Generate interviewer follow-up using Groq
    const aiText = await generateInterviewerResponse(
      interview.githubMetadata,
      formattedTurns,
      undefined,
      interview.difficulty || "Medium"
    );

    // 4 & 5. Concurrently save AI follow-up message in MongoDB and synthesize voice
    const [, tts] = await Promise.all([
      Message.create({
        interviewId,
        type: "Assistant",
        message: aiText,
      }),
      synthesizeSpeech(aiText),
    ]);

    res.json({
      aiMessage: aiText,
      audioBase64: tts ? tts.audioBuffer.toString("base64") : null,
      contentType: tts?.contentType || "audio/mp3",
    });
  } catch (error: any) {
    console.error("Process interview response error:", error);
    res.status(500).json({ message: error.message || "Failed to process interview response" });
  }
}

