/**
 * Lists user's past interviews
 */
export async function getMyInterviews(req: AuthRequest, res: Response): Promise<void> {
  try {
    if (!req.user) {
      res.status(401).json({ message: "Not authenticated" });
      return;
    }

    const interviews = await Interview.find({ userId: req.user._id })
      .sort({ createdAt: -1 })
      .lean();

    const interviewIds = interviews.map((i) => i._id);
    const messages = await Message.find({ interviewId: { $in: interviewIds } })
      .sort({ createdAt: 1 })
      .lean();

    const messagesByInterview: Record<string, any[]> = {};
    for (const msg of messages) {
      const key = msg.interviewId.toString();
      if (!messagesByInterview[key]) {
        messagesByInterview[key] = [];
      }
      messagesByInterview[key].push({
        id: msg._id.toString(),
        type: msg.type,
        message: msg.message,
        createdAt: msg.createdAt,
      });
    }

    const interviewsWithMessages = interviews.map((i) => ({
      ...i,
      messages: messagesByInterview[i._id.toString()] || [],
    }));

    res.json({
      success: true,
      interviews: interviewsWithMessages,
    });
  } catch (error: any) {
    console.error("Get my interviews error:", error);
    res.status(500).json({ message: error.message || "Failed to fetch user interviews" });
  }
}

/**
 * Corrects STT transcript errors for technical terms using Groq AI.
 * Only fixes misheared proper nouns / tech terms — never rewrites content.
 */
export async function correctTranscript(req: Request, res: Response): Promise<void> {
  try {
    const { text } = req.body as { text?: string };
    if (!text || !text.trim()) {
      res.status(400).json({ message: "text is required" });
      return;
    }

    const { callGroqWithFallback } = await import("../services/groqService");

    const completion = await callGroqWithFallback((groq) =>
      groq.chat.completions.create({
        model: "openai/gpt-oss-20b",
        messages: [
          {
            role: "system",
            content: `You are a technical transcript corrector for a developer interview. 
Your ONLY job is to fix speech recognition errors for technical terms, proper nouns, brand names, and programming concepts.

Rules (strictly follow):
- ONLY fix words that are clearly misheared technical/proper nouns (e.g. "mongo" → "MongoDB", "react" → "React", "node" → "Node.js", "express" → "Express.js", "java script" → "JavaScript", "type script" → "TypeScript", "post gres" → "PostgreSQL", "my sequel" → "MySQL", "git hub" → "GitHub", "docker" → "Docker", "kube" → "Kubernetes", "rest api" → "REST API", "jay son" → "JSON", "html" → "HTML", "css" → "CSS", "next js" → "Next.js").
- Do NOT rephrase, rewrite, add, or remove any content.
- Do NOT fix grammar or punctuation.
- Do NOT change words that are already correct.
- Return ONLY the corrected text, nothing else. No explanation, no quotes.`,
          },
          {
            role: "user",
            content: text.trim(),
          },
        ],
        temperature: 0.1,
        max_tokens: 500,
      })
    );

    const corrected = completion?.choices[0]?.message?.content?.trim() || text;
    res.json({ corrected });
  } catch (error: any) {
    console.error("Transcript correction error:", error);
    // On any error, return the original text so the interview is never blocked
    const { text } = req.body as { text?: string };
    res.json({ corrected: text || "" });
  }
}
